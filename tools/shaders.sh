#!/bin/sh
# Usage: tools/shaders.sh [--check]
# Compiles the GLSL in src/render/gpu/shaders to SPIR-V headers beside it, which the build includes.
# With --check it only reports headers that differ from what the GLSL compiles to.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
DIR=$ROOT/src/render/gpu/shaders
CHECK=0

[ "${1:-}" = --check ] && CHECK=1

command -v glslangValidator >/dev/null || { echo "glslangValidator not found" >&2; exit 1; }

SPIRV=${TMPDIR:-/tmp}/tiv-shaders.spv
OUT=${TMPDIR:-/tmp}/tiv-shaders.h
STALE=0

for source in "$DIR"/*.vert "$DIR"/*.frag; do
    file=$(basename "$source")
    name=$(printf '%s' "$file" | tr . _ | tr '[:lower:]' '[:upper:]')
    header=$DIR/$file.h
    glslangValidator -V --target-env vulkan1.1 --quiet -o "$SPIRV" "$source" >/dev/null
    words=$(od -An -v -tx4 "$SPIRV" | tr -s ' \n' ' ' | sed -e 's/^ //' -e 's/ $//' | tr ' ' '\n' | sed 's/^/0x/')
    count=$(printf '%s\n' "$words" | wc -l)

    {
        printf '// Generated by tools/shaders.sh from %s. Do not edit.\n' "$file"
        printf '#include <array>\n#include <cstdint>\n\nnamespace tiv::gpu::Spirv {\n\n'
        printf 'inline constexpr std::array<std::uint32_t, %d> %s = {\n' "$count" "$name"
        printf '%s\n' "$words" | paste -d, - - - - - - - - | sed -e 's/,*$/,/' -e 's/,/, /g' -e 's/^/        /' -e 's/ $//'
        printf '};\n\n}\n'
    } > "$OUT"

    if [ "$CHECK" = 1 ]; then
        cmp -s "$OUT" "$header" || { echo "stale: $header" >&2; STALE=1; }
    else
        cp "$OUT" "$header"
    fi
done

exit "$STALE"
